const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errs = []; p.on('console', m => m.type() === 'error' && errs.push(m.text())); p.on('pageerror', e => errs.push(e.message));
  const out = process.argv[2];
  await p.goto(process.env.APP_URL || 'http://localhost:5173'); await p.waitForTimeout(600);
  await p.getByRole('button', { name: /Request/ }).click();
  await p.screenshot({ path: out + '/4-request.png', fullPage: true });
  await p.fill('#price', '10'); await p.getByRole('button', { name: 'Send request' }).click();
  console.log('low price error:', await p.locator('.error').innerText());
  await p.fill('#price', '300'); await p.getByRole('button', { name: 'Send request' }).click();
  await p.waitForTimeout(300); await p.screenshot({ path: out + '/5-sending.png' });
  await p.waitForTimeout(1300);
  console.log('heading:', await p.locator('h1').innerText(), '| cards', await p.locator('.offer').count());
  console.log('tags:', await p.locator('.tag').allInnerTexts());
  await p.screenshot({ path: out + '/6-offers.png', fullPage: true });
  await p.getByRole('button', { name: /Choose this offer/ }).nth(2).click(); await p.waitForTimeout(300);
  console.log('after choose:', await p.locator('h1').innerText());
  console.log('scrollWidth', await p.evaluate(() => document.documentElement.scrollWidth), 'errors', errs);
  await b.close();
})();

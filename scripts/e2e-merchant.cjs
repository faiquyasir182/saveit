const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const errs = []; p.on('console', m => m.type() === 'error' && errs.push(m.text())); p.on('pageerror', e => errs.push(e.message));
  const out = process.argv[2];
  await p.goto(process.env.APP_URL || 'http://localhost:5173'); await p.waitForTimeout(600);
  await p.getByRole('button', { name: 'Merchant view (demo)' }).click();
  const r31 = p.getByLabel('Request R-31');
  console.log('accept disabled below min:', await r31.getByRole('button', { name: 'Accept' }).isDisabled());
  await r31.getByRole('button', { name: 'Counter' }).click();
  await r31.locator('input').fill('250'); await r31.getByRole('button', { name: 'Send counteroffer' }).click();
  console.log('low counter:', await r31.locator('.error').innerText());
  await r31.locator('input').fill('300'); await r31.getByRole('button', { name: 'Send counteroffer' }).click();
  console.log('sent:', await r31.getByRole('status').innerText());
  await p.getByLabel('Request R-32').getByRole('button', { name: 'Accept' }).click();
  await p.screenshot({ path: out + '/9-merchant-requests.png', fullPage: true });
  await p.getByRole('tab', { name: 'Orders' }).click();
  await p.getByRole('button', { name: 'Accept order' }).click();
  console.log('order tags:', await p.locator('.tag').allInnerTexts());
  await p.getByRole('tab', { name: 'Listings' }).click();
  await p.getByRole('button', { name: /Increase quantity/ }).click(); await p.getByRole('button', { name: 'Pause' }).click();
  console.log('listing:', (await p.locator('article').first().innerText()).replace(/\n/g, ' | '));
  await p.screenshot({ path: out + '/10-merchant-listings.png', fullPage: true });
  console.log('scrollWidth', await p.evaluate(() => document.documentElement.scrollWidth), 'errors', errs);
  await b.close();
})();
